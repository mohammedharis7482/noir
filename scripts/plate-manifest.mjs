// Lists the photographs in public/images/plates in src/content/plate-files.ts,
// so NoirImage knows which plates exist without touching the file system and
// works the same in server and client components. `npm run dev` and
// `npm run build` run this first; while the dev server is running, run
// `npm run plates` after adding photographs.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const folder = new URL("../public/images/plates/", import.meta.url);
const target = new URL("../src/content/plate-files.ts", import.meta.url);

const files = readdirSync(folder)
  .filter((name) => name.endsWith(".jpg"))
  .sort();

const entries = files.map((name) => `  ${JSON.stringify(name)},\n`).join("");
const source = `// Generated by scripts/plate-manifest.mjs from public/images/plates.
// Do not edit: \`npm run dev\`, \`npm run build\` and \`npm run plates\` rewrite it.
export const plateFiles: readonly string[] = [${entries ? `\n${entries}` : ""}];
`;

let current = "";
try {
  current = readFileSync(target, "utf8");
} catch {
  // First run: the manifest does not exist yet.
}
if (current !== source) writeFileSync(target, source);

const count = `${files.length} photograph${files.length === 1 ? "" : "s"}`;
console.log(`plates: ${count} in public/images/plates`);
